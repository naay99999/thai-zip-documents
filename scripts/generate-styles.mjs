// Copies the component templates out of the installed react-thaizip package
// into .generated/, the way `react-thaizip add` copies them into a project:
//
// - .generated/templates/  — the vanilla templates plus lib/ and hooks/, which
//   the `@/components/*` and `@/*` tsconfig aliases point at.
// - .generated/styles/<base>/ — each shadcn/ui variant next to the shadcn
//   primitives it composes (vendored in vendor/shadcn/<base>/), so the site can
//   render every style side by side. All three bases import the same
//   `@/components/ui/*` specifiers but need different primitives, which one
//   tsconfig alias can't express — so each copy gets those imports rewritten to
//   its own base's primitives.
//
// Next.js doesn't compile TypeScript inside node_modules, which is why the
// templates are copied out instead of imported from the package directly.
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const docsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const packageRoot = path.dirname(createRequire(import.meta.url).resolve('react-thaizip/package.json'))
const templates = path.join(packageRoot, 'templates/react/ts')
const vendoredPrimitives = path.join(docsRoot, 'vendor/shadcn')
const outputRoot = path.join(docsRoot, '.generated')
const BASES = ['base', 'radix', 'aria']

const HEADER = '// Generated by scripts/generate-styles.mjs from the react-thaizip package — do not edit.\n'

function rewriteUiImports(source, prefix) {
  return source.replace(/(['"])@\/components\/ui\/([^'"]+)\1/g, (_, quote, name) => `${quote}${prefix}${name}${quote}`)
}

async function copyDirectory(from, to, prefix) {
  await mkdir(to, { recursive: true })
  for (const file of await readdir(from)) {
    if (!file.endsWith('.tsx')) continue
    const source = await readFile(path.join(from, file), 'utf8')
    // A leading 'use client' directive must stay the first statement.
    const output = rewriteUiImports(source, prefix).replace(/^(['"]use client['"];?\n)?/, (directive) => `${directive}${HEADER}`)
    await writeFile(path.join(to, file), output)
  }
}

await rm(outputRoot, { recursive: true, force: true })
await cp(templates, path.join(outputRoot, 'templates'), {
  recursive: true,
  filter: (source) => path.basename(source) !== 'shadcn',
})
for (const base of BASES) {
  const target = path.join(outputRoot, 'styles', base)
  await copyDirectory(path.join(templates, 'shadcn', base), target, './ui/')
  await copyDirectory(path.join(vendoredPrimitives, base), path.join(target, 'ui'), './')
}
